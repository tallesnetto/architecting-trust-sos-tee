"""Builds the LaTeX tables and in-text macros from the CSV files in results/."""
import collections
import statistics

from .common import GENERATED, read_csv
from .e2_overhead import CONFIGS

SIZES = ["S", "M", "L"]

SCENARIO_ROWS = [
    ("CUI1", "MC1", "Divergent software receives data", "DP1"),
    ("CUI2", "MC2", "Infrastructure reads patient data", "DP2"),
    ("CUI3a", "MC3a", "Record tampered in transit", "DP3"),
    ("CUI3b", "MC3b", "Record altered by its custodian", "DP3"),
    ("CUI3c", "MC3c", "Record with a forged origin", "DP3"),
    ("CUI4", "MC4", "Gateway changed after integration", "DP4"),
    ("CUI5", "MC5", "Data used for another purpose", "DP5"),
    ("EV1", "EV1", "Agreed update (must pass)", "DP5"),
]
LABELS = {"B0": "Baseline", "FULL": "Full model"}


def _write(name, text):
    GENERATED.mkdir(parents=True, exist_ok=True)
    (GENERATED / name).write_text(text, encoding="utf-8")


def _macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def _cell(harmed, legitimate):
    if legitimate:
        return r"\harm{rejected}" if harmed else r"\safe{accepted}"
    return r"\harm{harm}" if harmed else r"\safe{blocked}"


def e1(macros):
    rows = read_csv("e1_threats.csv")
    harm = collections.defaultdict(list)
    for r in rows:
        harm[(r["scenario"], r["config"])].append(int(r["harm"]))
    harmed = {k: any(v) for k, v in harm.items()}

    lines = [r"\begin{tabularx}{\columnwidth}{@{}>{\raggedright\arraybackslash}X l cc@{}}",
             r"\toprule",
             r"Misuse case & Principle & Baseline & Full model \\",
             r"\midrule"]
    for code, name, text, dp in SCENARIO_ROWS:
        ev = code == "EV1"
        cells = [_cell(harmed[(code, c)], ev) for c in ("B0", "FULL")]
        lines.append(f"{name} {text} & {dp} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabularx}"]
    _write("e1_table.tex", "\n".join(lines) + "\n")

    # statements made in the paper
    assert not any(harmed[(c, "FULL")] and c != "EV1" for c, *_ in SCENARIO_ROWS)
    assert not harmed[("EV1", "FULL")] and not harmed[("CUI3a", "B0")]
    assert all(harmed[(c, "B0")] for c, *_ in SCENARIO_ROWS if c not in ("CUI3a", "EV1"))
    macros += [_macro("EOneRuns", len(rows)), _macro("EOneScenarios", len(SCENARIO_ROWS))]


def _block_median(rows, key, value):
    per_block = collections.defaultdict(list)
    for r in rows:
        per_block[(key(r), r["block"])].append(value(r))
    out = collections.defaultdict(list)
    for (k, _), v in per_block.items():
        out[k].append(statistics.median(v))
    return {k: statistics.median(v) for k, v in out.items()}


def e2(macros):
    rows = read_csv("e2_exchange.csv")
    hs_rows = read_csv("e2_handshake.csv")
    cell = lambda r: (r["config"], r["size"])
    med = _block_median(rows, cell, lambda r: float(r["latency_us"]))
    mwire = _block_median(rows, cell, lambda r: int(r["wire_bytes"]))
    payload = _block_median(rows, lambda r: r["size"], lambda r: int(r["payload_bytes"]))
    hs = _block_median(hs_rows, lambda r: r["config"], lambda r: float(r["latency_us"]))
    blocks = len({r["block"] for r in rows})

    lines = [r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lrrrrrrr@{}}", r"\toprule",
             r" & \multicolumn{3}{c}{Time per record (ms)} & \multicolumn{3}{c}{Size on the wire (KiB)}"
             r" & Channel \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
             r"Configuration & S & M & L & S & M & L & setup (ms) \\", r"\midrule"]
    for c in CONFIGS:
        cells = [f"{med[(c, s)] / 1000:.2f}" for s in SIZES]
        cells += [f"{mwire[(c, s)] / 1024:.1f}" for s in SIZES]
        cells.append(f"{hs[c] / 1000:.2f}")
        lines.append(LABELS[c] + " & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular*}"]
    _write("e2_table.tex", "\n".join(lines) + "\n")

    for s in SIZES:
        name = {"S": "Small", "M": "Medium", "L": "Large"}[s]
        base, full = med[("B0", s)], med[("FULL", s)]
        macros += [_macro(f"Payload{name}KiB", f"{payload[s] / 1024:.1f}"),
                   _macro(f"Full{name}ms", f"{full / 1000:.2f}"),
                   _macro(f"Base{name}ms", f"{base / 1000:.2f}"),
                   _macro(f"Delta{name}ms", f"{(full - base) / 1000:.1f}"),
                   _macro(f"Rel{name}pct", f"{100 * (full - base) / base:.0f}"),
                   _macro(f"Wire{name}Extra", f"{(mwire[('FULL', s)] - mwire[('B0', s)]) / 1024:.1f}")]
    macros += [_macro("HandshakeFullms", f"{hs['FULL'] / 1000:.2f}"),
               _macro("HandshakeBasems", f"{hs['B0'] / 1000:.2f}"),
               _macro("ETwoBlocks", blocks),
               _macro("ETwoRecords", len(rows) // (blocks * len(CONFIGS) * len(SIZES))),
               _macro("ETwoHandshakes", len(hs_rows) // (blocks * len(CONFIGS)))]


def main():
    macros = ["% Generated by experiments/report.py -- do not edit\n"]
    e1(macros)
    e2(macros)
    _write("macros.tex", "".join(macros))
    print(f"wrote {GENERATED}")


if __name__ == "__main__":
    main()
